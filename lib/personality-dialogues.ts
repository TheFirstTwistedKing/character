export function catalogIqLine(line: string, scene: number, variant: number, iq: number, polite: boolean) {
  const band = iq < 100 ? "low" : iq >= 120 ? "high" : null;
  if (!band) return line;
  const extra = dialoguePair(IQ_BEATS[band][scene][variant % 5])[polite ? 1 : 0];
  return `${line} ${extra}`;
}
