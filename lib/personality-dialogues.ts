export type DialoguePair = [string, string];
function politeClause(value: string) {
  const pronouns: Record<string, string> = { "나는":"저는", "내가":"제가", "나를":"저를", "나도":"저도", "나만":"저만", "나에게":"저에게", "나야":"저야", "너에게":"당신에게", "너를":"당신을", "너와":"당신과", "네가":"당신이", "네게":"당신에게", "네게서":"당신에게서", "내":"제", "네":"당신의", "나":"저", "너":"당신" };
  let result = value.split(" ").map(word => pronouns[word] ?? word).join(" ");
  if (result.endsWith("이야")) return result.slice(0,-2) + "이에요";
  if (result.endsWith("야")) return result.slice(0,-1) + "예요";
  return result + "요";
}
// Only authored conversational clauses are accepted here, not arbitrary user text.
export function dialoguePair(stem: string): DialoguePair {
  const clauses = stem.split(/\.\s*/).filter(Boolean);
  const casual = clauses.map(s => s + (s.endsWith("까") ? "?" : ".")).join(" ");
  const polite = clauses.map(s => politeClause(s) + (s.endsWith("까") ? "?" : ".")).join(" ");
  return [casual, polite];
}
export function catalogDialogueLines(key: string): [DialoguePair[], DialoguePair[], DialoguePair[]] {
  const [tone, ...anchors] = TRAIT_ANCHORS[key];
  return anchors.map((anchor, scene) => BEATS[tone][scene].map(beat => {
    const lead = dialoguePair(anchor), tail = dialoguePair(beat);
    return [`${lead[0]} ${tail[0]}`, `${lead[1]} ${tail[1]}`] as DialoguePair;
  })) as [DialoguePair[], DialoguePair[], DialoguePair[]];
}

